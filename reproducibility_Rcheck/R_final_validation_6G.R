args <- commandArgs(trailingOnly = TRUE)
target_lib <- args[[1]]
lockfile <- args[[2]]
library(renv, lib.loc = Sys.getenv('R_LIBS_USER'))
options(width = 120)
lock <- renv::lockfile_read(lockfile)
installed <- utils::installed.packages(lib.loc = target_lib)
locked <- vapply(lock$Packages, function(x) x$Version, character(1))
common <- intersect(names(locked), rownames(installed))
missing <- setdiff(names(locked), rownames(installed))
mismatch <- common[locked[common] != installed[common, 'Version']]
cat('R_VERSION=', R.version.string, '\n', sep = '')
cat('LOCKFILE_PACKAGES=', length(locked), '\n', sep = '')
cat('TARGET_LIBRARY_PACKAGES=', nrow(installed), '\n', sep = '')
cat('MATCHING_LOCKED_VERSIONS=', length(common) - length(mismatch), '\n', sep = '')
cat('MISSING_FROM_TARGET_LIBRARY=', length(missing), '\n', sep = '')
if (length(missing)) cat('MISSING=', paste(missing, collapse = ', '), '\n', sep = '')
cat('VERSION_MISMATCHES=', length(mismatch), '\n', sep = '')
if (length(mismatch)) for (p in mismatch) cat('MISMATCH ', p, ': locked=', locked[[p]], ' installed=', installed[p, 'Version'], '\n', sep = '')
for (p in c('BiocManager', 'BiocVersion', 'Rcpp', 'Seurat', 'SingleCellExperiment', 'spatialLIBD', 'sf', 's2', 'classInt', 'wk'))
  cat('CHECK ', p, '=', if (p %in% rownames(installed)) installed[p, 'Version'] else 'NOT IN TARGET LIBRARY', '\n', sep = '')
cat('NOTE: missing entries are checked separately against R base/recommended packages in the system library.\n')
